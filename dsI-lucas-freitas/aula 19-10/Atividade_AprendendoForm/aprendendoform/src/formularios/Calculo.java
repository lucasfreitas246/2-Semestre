    private void btn_DivisaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_DivisaoActionPerformed
        // TODO add your handling code here:
        int x, y, z; // Variáveis de apoio
        String r; // R string para receber valor

        try {
            x = Integer.parseInt(txt_n1.getText()); // Mesclando o Campo com a variável
            y = Integer.parseInt(txt_n2.getText());

            if (y == 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Não é possível divisão por zero!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
                txt_res.setText("Erro: Divisão por 0");
            } else {
                z = x / y; // operação
                r = String.valueOf(z); // passando a variável para String para que o campo de texto seja aceito
                txt_res.setText(r); // Campo de resposta recebendo valor
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, digite valores numéricos válidos!", "Erro", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btn_DivisaoActionPerformed

