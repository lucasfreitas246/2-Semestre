    private void btn_CompararActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_CompararActionPerformed
        // TODO add your handling code here:
        int x, y;
        try {
            x = Integer.parseInt(txt_n1.getText());
            y = Integer.parseInt(txt_n2.getText());

            if (x > y) {
                txt_res.setText("N1 (" + x + ") é maior que N2 (" + y + ")");
            } else if (x < y) {
                txt_res.setText("N2 (" + y + ") é maior que N1 (" + x + ")");
            } else {
                txt_res.setText("N1 e N2 são iguais (" + x + ")");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, digite valores numéricos válidos!", "Erro", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btn_CompararActionPerformed

